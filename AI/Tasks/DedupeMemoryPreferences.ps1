#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Deduplicates near-duplicate preference entries in TechToolbox AI memory.

.DESCRIPTION
    Scans the preferences object in memory.json and removes entries that express
    the same intent with minor wording differences.

    By default, the script runs in preview mode and does not modify files.
    Use -Apply to persist deduplicated preferences back to memory.json.

.PARAMETER MemoryPath
    Path to the memory.json file (default: AI/memory.json in repo root).

.PARAMETER Apply
    When provided, writes deduplicated preferences back to memory.json.

.EXAMPLE
    .\DedupeMemoryPreferences.ps1

    Preview duplicate preference entries without changing files.

.EXAMPLE
    .\DedupeMemoryPreferences.ps1 -Apply

    Apply deduplication changes and save memory.json.
#>

param(
    [string]$MemoryPath = "$PSScriptRoot/../memory.json",
    [switch]$Apply
)

$ErrorActionPreference = 'Stop'

function Normalize-ForComparison {
    param([string]$Value)

    if ([string]::IsNullOrWhiteSpace($Value)) {
        return ''
    }

    $lowered = $Value.ToLowerInvariant()
    $cleaned = [regex]::Replace($lowered, '[^a-z0-9]+', ' ')
    return ([regex]::Replace($cleaned, '\s+', ' ')).Trim()
}

function Get-CommonLeadingTokenCount {
    param(
        [string]$Left,
        [string]$Right
    )

    $leftTokens = @($Left.Split(' ', [System.StringSplitOptions]::RemoveEmptyEntries))
    $rightTokens = @($Right.Split(' ', [System.StringSplitOptions]::RemoveEmptyEntries))
    $max = [Math]::Min($leftTokens.Count, $rightTokens.Count)
    $count = 0

    for ($i = 0; $i -lt $max; $i++) {
        if ($leftTokens[$i] -ne $rightTokens[$i]) {
            break
        }

        $count++
    }

    return $count
}

function Get-CommonLeadingCharCount {
    param(
        [string]$Left,
        [string]$Right
    )

    $max = [Math]::Min($Left.Length, $Right.Length)
    $count = 0

    for ($i = 0; $i -lt $max; $i++) {
        if ($Left[$i] -ne $Right[$i]) {
            break
        }

        $count++
    }

    return $count
}

function Test-EquivalentPreference {
    param(
        [string]$Left,
        [string]$Right
    )

    if ([string]::Equals($Left, $Right, [System.StringComparison]::OrdinalIgnoreCase)) {
        return $true
    }

    $normalizedLeft = Normalize-ForComparison -Value $Left
    $normalizedRight = Normalize-ForComparison -Value $Right

    if ($normalizedLeft -eq $normalizedRight) {
        return $true
    }

    if ($normalizedLeft.Length -ge 24 -and $normalizedRight.Length -ge 24) {
        if ($normalizedLeft.Contains($normalizedRight) -or $normalizedRight.Contains($normalizedLeft)) {
            return $true
        }

        $commonTokenCount = Get-CommonLeadingTokenCount -Left $normalizedLeft -Right $normalizedRight
        $commonCharCount = Get-CommonLeadingCharCount -Left $normalizedLeft -Right $normalizedRight

        if ($commonTokenCount -ge 6 -and $commonCharCount -ge 24) {
            return $true
        }
    }

    return $false
}

function Get-PreferenceEntries {
    param([object]$Preferences)

    $entries = @()

    if ($null -eq $Preferences) {
        return $entries
    }

    if ($Preferences -is [System.Collections.IDictionary]) {
        foreach ($key in $Preferences.Keys) {
            $entries += [PSCustomObject]@{
                Key   = [string]$key
                Value = [string]$Preferences[$key]
            }
        }

        return $entries
    }

    foreach ($prop in $Preferences.PSObject.Properties) {
        $entries += [PSCustomObject]@{
            Key   = [string]$prop.Name
            Value = [string]$prop.Value
        }
    }

    return $entries
}

# Resolve path and load memory
$MemoryPath = (Resolve-Path -LiteralPath $MemoryPath -ErrorAction Stop).Path
$memory = Get-Content -LiteralPath $MemoryPath -Raw | ConvertFrom-Json -AsHashtable -DateKind String

if ($null -eq $memory['preferences']) {
    Write-Host 'No preferences object found. Nothing to deduplicate.' -ForegroundColor Yellow
    exit 0
}

$entries = Get-PreferenceEntries -Preferences $memory['preferences']

if ($entries.Count -eq 0) {
    Write-Host 'No preference entries found. Nothing to deduplicate.' -ForegroundColor Yellow
    exit 0
}

$kept = [ordered]@{}
$removed = New-Object System.Collections.Generic.List[object]

foreach ($entry in $entries) {
    $match = $null
    foreach ($keptKey in $kept.Keys) {
        if (Test-EquivalentPreference -Left $kept[$keptKey] -Right $entry.Value) {
            $match = $keptKey
            break
        }
    }

    if ($null -ne $match) {
        $removed.Add(
            [PSCustomObject]@{
                RemovedKey   = $entry.Key
                RemovedValue = $entry.Value
                KeptKey      = $match
                KeptValue    = $kept[$match]
            }
        )
        continue
    }

    $kept[$entry.Key] = $entry.Value
}

Write-Host 'TechToolbox Memory Preference Dedupe' -ForegroundColor Cyan
Write-Host '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━'
Write-Host ("Memory file: {0}" -f $MemoryPath)
Write-Host ("Original preference count: {0}" -f $entries.Count)
Write-Host ("Deduplicated preference count: {0}" -f $kept.Count)
Write-Host ("Duplicate entries identified: {0}" -f $removed.Count)

if ($removed.Count -gt 0) {
    Write-Host ''
    Write-Host 'Sample duplicates:' -ForegroundColor Yellow

    foreach ($item in $removed | Select-Object -First 10) {
        Write-Host ("  - Removed: {0}" -f $item.RemovedKey)
        Write-Host ("    Value: {0}" -f $item.RemovedValue)
        Write-Host ("    Kept:  {0}" -f $item.KeptKey)
    }

    if ($removed.Count -gt 10) {
        Write-Host ("  ...and {0} more" -f ($removed.Count - 10))
    }
}

if (-not $Apply.IsPresent) {
    Write-Host ''
    Write-Host 'Preview mode only. No file changes were made.' -ForegroundColor Yellow
    Write-Host 'Run with -Apply to persist the deduplicated preferences.' -ForegroundColor Yellow
    exit 0
}

if ($removed.Count -eq 0) {
    Write-Host ''
    Write-Host 'No duplicates found. No file changes were required.' -ForegroundColor Green
    exit 0
}

# Persist updated preferences while leaving facts/history intact
$memory['preferences'] = $kept
$memory | ConvertTo-Json -Depth 20 | Set-Content -LiteralPath $MemoryPath -Encoding utf8

Write-Host ''
Write-Host 'Saved deduplicated preferences to memory.json.' -ForegroundColor Green

