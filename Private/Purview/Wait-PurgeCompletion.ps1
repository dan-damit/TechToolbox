function Wait-PurgeCompletion {
    [CmdletBinding(DefaultParameterSetName = 'BySearch')]
    param(
        [Parameter(ParameterSetName = 'BySearch', Mandatory)][string]$SearchName,
        [Parameter(ParameterSetName = 'ByAction', Mandatory)][string]$ActionIdentity,
        [string]$CaseName,
        [ValidateRange(1, 86400)][int]$TimeoutSeconds = 2400,
        [ValidateRange(1, 3600)][int]$PollSeconds = 15
    )

    # Capture param-set decision ONCE (do not rely on $PSCmdlet inside a later scriptblock)
    $byAction = $PSCmdlet.ParameterSetName -eq 'ByAction'

    $target = if ($byAction) { $ActionIdentity } else { $SearchName }

    function Get-PurgeScope {
        if ([string]::IsNullOrWhiteSpace($CaseName)) {
            Get-ComplianceSearchAction -Purge -Details -ErrorAction SilentlyContinue
        }
        else {
            Get-ComplianceSearchAction -Purge -Case $CaseName -Details -ErrorAction SilentlyContinue
        }
    }

    # Helper: try to find an action by GUID/name/id from the purge scope
    function Resolve-PurgeAction {
        param(
            [Parameter(Mandatory)][string]$IdOrName
        )

        # First try direct lookup (works if caller passed an actual action identity/name)
        $direct = Get-ComplianceSearchAction -Identity $IdOrName -Details -ErrorAction SilentlyContinue
        if ($direct) { return $direct }

        # If it's a GUID or unknown token, scan the purge scope and match common fields
        $scope = Get-PurgeScope
        if (-not $scope) { return $null }

        $scope |
        Where-Object {
            ($_.Identity -eq $IdOrName) -or
            ($_.Name -eq $IdOrName) -or
            ($_.JobId -eq $IdOrName) -or
            ($_.RunId -eq $IdOrName) -or
            # last-resort: sometimes the GUID appears inside Identity
            ($_.Identity -like "*$IdOrName*")
        } |
        Sort-Object CreatedTime -Descending |
        Select-Object -First 1
    }

    $poll = {
        if ($byAction) {
            Resolve-PurgeAction -IdOrName $ActionIdentity
        }
        else {
            $scope = Get-PurgeScope
            $scope |
            Where-Object { $_.SearchName -eq $SearchName } |
            Sort-Object CreatedTime -Descending |
            Select-Object -First 1
        }
    }

    $getStatus = {
        param($obj)

        if (-not $obj) { return $null }

        # If JobEndTime is set, the purge execution has finished, regardless of .Status
        if ($obj.JobEndTime) {
            if (-not [string]::IsNullOrWhiteSpace($obj.Errors)) {
                # Execution finished but with errors
                return 'CompletedWithErrors'
            }

            # No errors – treat as Completed even if .Status still says InProgress
            return 'Completed'
        }

        # Otherwise, fall back to the current Status field
        return [string]$obj.Status
    }

    function Format-PurgeResultsText {
        param(
            [AllowNull()][string]$Results
        )

        if ([string]::IsNullOrWhiteSpace($Results)) {
            return $Results
        }

        $formatted = $Results.Trim()
        $formatted = $formatted -replace ',\s*', ",`n"
        $formatted = $formatted -replace '\{\s*', "{`n"
        $formatted = $formatted -replace '\s*\}', "`n}"

        return $formatted.Trim()
    }

    $terminal = @{
        'Completed'           = @{
            Level   = 'Warn'
            Message = {
                param($obj, $status)

                $results = $obj.Results
                $itemCount = $null

                if ($results -match 'Item count:\s*(\d+)') {
                    $itemCount = [int]$matches[1]
                }

                $formattedResults = Format-PurgeResultsText -Results $results

                if ($itemCount -ne $null) {
                    "Purge '$target' completed. Items processed: $itemCount.`nResults:`n$formattedResults"
                }
                else {
                    "Purge '$target' completed.`nResults:`n$formattedResults"
                }
            }
        }
        'CompletedWithErrors' = @{
            Level   = 'Warn'
            Message = {
                param($obj, $status)

                $formattedErrors = Format-PurgeResultsText -Results $obj.Errors
                $formattedResults = Format-PurgeResultsText -Results $obj.Results

                if ([string]::IsNullOrWhiteSpace($formattedResults)) {
                    "Purge '$target' completed with errors.`nErrors:`n$formattedErrors"
                }
                else {
                    "Purge '$target' completed with errors.`nErrors:`n$formattedErrors`nResults:`n$formattedResults"
                }
            }
        }
        'PartiallySucceeded'  = @{
            Level   = 'Warn'
            Message = {
                param($obj, $status)

                $formattedErrors = Format-PurgeResultsText -Results $obj.Errors
                $formattedResults = Format-PurgeResultsText -Results $obj.Results

                if ([string]::IsNullOrWhiteSpace($formattedResults)) {
                    "Purge '$target' partially succeeded.`nErrors:`n$formattedErrors"
                }
                else {
                    "Purge '$target' partially succeeded.`nErrors:`n$formattedErrors`nResults:`n$formattedResults"
                }
            }
        }
        'Failed'              = @{
            Level   = 'Error'
            Message = {
                param($obj, $status)

                $formattedErrors = Format-PurgeResultsText -Results $obj.Errors
                $formattedResults = Format-PurgeResultsText -Results $obj.Results

                if ([string]::IsNullOrWhiteSpace($formattedResults)) {
                    "Purge '$target' failed.`nErrors:`n$formattedErrors"
                }
                else {
                    "Purge '$target' failed.`nErrors:`n$formattedErrors`nResults:`n$formattedResults"
                }
            }
        }
    }

    $ctxFmt = {
        param($lastObj, $lastStatus)
        if ($lastObj) {
            "LastSeen: Name=$($lastObj.Name) Identity=$($lastObj.Identity) Status=$($lastObj.Status) Errors=$($lastObj.Errors)"
        }
        else {
            "Purge object was never discovered."
        }
    }

    $waitParams = @{
        Target           = $target
        PollScript       = $poll
        GetStatus        = $getStatus
        TerminalStates   = $terminal
        TimeoutSeconds   = $TimeoutSeconds
        PollSeconds      = $PollSeconds
        NotFoundMessage  = "Purge not found yet..."
        ContextFormatter = $ctxFmt
    }

    Wait-TerminalState @waitParams
}

